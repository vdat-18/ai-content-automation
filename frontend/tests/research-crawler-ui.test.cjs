  assert.match(page, /className="research-progress"/);
  assert.match(catalog, /className="research-record-grid"/);
  assert.match(catalog, /<img src=\{imageUrl\}/);
  assert.match(catalog, /currentTime = 0\.1/);
  assert.match(catalog, /<video key=\{url\} src=\{url\} controls/);
