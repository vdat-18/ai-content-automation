function interpolate(value: string, variables?: Record<string, string | number>) {
  if (!variables) return value;
  return Object.entries(variables).reduce((result, [key, replacement]) => result.replaceAll(`{${key}}`, String(replacement)), value);
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, updateLanguage] = useState<Language>(() => {
    const saved = localStorage.getItem(LANGUAGE_KEY);
    if (saved === "en" || saved === "vi") return saved;
    return navigator.language.toLowerCase().startsWith("vi") ? "vi" : "en";
  });
  const locale = language === "vi" ? "vi-VN" : "en-US";
  const setLanguage = useCallback((next: Language) => {
    localStorage.setItem(LANGUAGE_KEY, next);
    updateLanguage(next);
  }, []);
  const t = useCallback((source: string, variables?: Record<string, string | number>) => interpolate(language === "vi" ? vi[source] ?? source : source, variables), [language]);
  const formatDate = useCallback((value: string | number | Date, options?: Intl.DateTimeFormatOptions) => new Intl.DateTimeFormat(locale, options ?? { dateStyle: "medium", timeStyle: "short" }).format(new Date(value)), [locale]);
  const formatNumber = useCallback((value: number, options?: Intl.NumberFormatOptions) => new Intl.NumberFormat(locale, options).format(value), [locale]);
  const formatCurrency = useCallback((value: number, currency = "USD") => new Intl.NumberFormat(locale, { style: "currency", currency, maximumFractionDigits: 2 }).format(value), [locale]);
  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);
  useEffect(() => {
    const sync = (event: StorageEvent) => {
      if (event.key === LANGUAGE_KEY && (event.newValue === "en" || event.newValue === "vi")) updateLanguage(event.newValue);
    };
    window.addEventListener("storage", sync);
    return () => window.removeEventListener("storage", sync);
  }, []);
  const value = useMemo<I18nValue>(() => ({ language, locale, setLanguage, t, formatDate, formatNumber, formatCurrency }), [language, locale, setLanguage, t, formatDate, formatNumber, formatCurrency]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}
